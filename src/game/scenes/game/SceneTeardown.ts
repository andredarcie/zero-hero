// O DESMONTE DA CENA: o motor não chama shutdown sozinho, então o restart passa por aqui e solta ouvintes, texturas
// e peças, em vez de vazá-los para a partida seguinte.

import * as Engine from '@/game/engine';
import { clearGameDebugApi } from '@/game/debug/debugHooks';
import { profiler } from '@/game/debug/Profiler';
import { setTimeScale } from '@/game/runtime/timeOfDay';
import { setCurrentWorld3D } from '@/game/render3d/World3D';
import type { GameScene } from '../GameScene';

export class SceneTeardown {
  public constructor(private readonly host: GameScene) {}

  public shutdown(): void {
    this.host.debug.clearDebugHooks?.();
    this.host.debug.clearDebugHooks = undefined;
    this.host.intro.disarmIntroSkip?.();
    if (this.host.boot.keepClockOnLeave) window.removeEventListener('pagehide', this.host.boot.keepClockOnLeave);
    this.host.boot.keepClockOnLeave = undefined;
    if (this.host.debug.debugApi) {
      clearGameDebugApi(this.host.debug.debugApi);
      this.host.debug.debugApi = undefined;
    }
    this.host.scale.off(Engine.Scale.Events.RESIZE, this.host.view.handleResize, this.host.view);
    // 3D teardown: stop the frame hook, drop the billboards, dispose the renderer.
    this.host.events.off(Engine.Scenes.Events.POST_UPDATE, this.host.view.render3D, this.host.view);
    this.host.events.off(Engine.Scenes.Events.PRE_UPDATE, profiler.frameStart, profiler);
    this.host.game.events.off(Engine.Core.Events.PRE_RENDER, this.host.view.handlePreRender, this.host.view);
    this.host.game.events.off(Engine.Core.Events.POST_RENDER, this.host.view.handlePostRender, this.host.view);
    this.host.game.events.off(Engine.Core.Events.VISIBLE, this.host.view.handleVisible, this.host.view);
    profiler.detach();
    this.host.view.fpsCounter?.destroy();
    this.host.view.fpsCounter = undefined;
    this.host.view.heroSilhouette?.destroy();
    this.host.view.heroSilhouette = undefined;
    this.host.heroBillboard?.destroy();
    this.host.heroBillboard = undefined;
    this.host.swordPlanting.plantedSword?.destroy();
    this.host.swordPlanting.plantedSword = undefined;
    this.host.swordPlanting.plantedSwordTile = undefined;
    for (const mark of this.host.marks.questMarks) mark.bb?.destroy();
    this.host.marks.questMarks.length = 0;
    this.host.questSetup.painterQuest?.destroy();
    this.host.questSetup.painterQuest = undefined;
    this.host.questSetup.lumberQuest?.destroy();
    this.host.questSetup.lumberQuest = undefined;
    this.host.questSetup.astronomerQuest?.destroy();
    this.host.questSetup.astronomerQuest = undefined;
    this.host.dialog.greetedNpcs.clear();
    this.host.camp.rest.reset();
    setTimeScale(1);
    this.host.questSetup.clearMug();
    this.host.valley.npcHomes?.destroy();
    this.host.valley.npcHomes = undefined;
    this.host.groundItems.npcHouseTiles = undefined;
    this.host.valley.valleyFinds?.destroy();
    this.host.valley.valleyFinds = undefined;
    this.host.valley.heroCamp?.destroy();
    this.host.valley.heroCamp = undefined;
    this.host.camp.catCare.destroy();
    this.host.valley.waterfall?.destroy();
    this.host.valley.waterfall = undefined;
    this.host.valley.koiPond?.destroy();
    this.host.valley.koiPond = undefined;
    this.host.valley.bigTrees?.destroy();
    this.host.valley.bigTrees = undefined;
    this.host.valley.woodFence?.destroy();
    this.host.valley.woodFence = undefined;
    this.host.valley.lumberYard?.destroy();
    this.host.valley.lumberYard = undefined;
    this.host.valley.oldForge?.destroy();
    this.host.valley.oldForge = undefined;
    this.host.valley.crashSite?.destroy();
    this.host.valley.crashSite = undefined;
    this.host.valley.birdLife?.destroy();
    this.host.valley.birdLife = undefined;
    this.host.valley.nature?.destroy();
    this.host.valley.nature = undefined;
    this.host.valley.weather?.destroy();
    this.host.valley.weather = undefined;
    this.host.valley.shownSeason = undefined;
    this.host.roastEnding.reunion?.destroy();
    this.host.roastEnding.reunion = undefined;
    this.host.questSetup.skyVisitor?.destroy();
    this.host.questSetup.skyVisitor = undefined;
    this.host.questSetup.fireVisitor?.destroy();
    this.host.questSetup.fireVisitor = undefined;
    for (const keeper of this.host.fire.fireKeepers.values()) keeper.visitor.destroy();
    this.host.fire.fireKeepers.clear();
    this.host.fire.keptLitFires.clear();
    this.host.intro.wizardStandIn?.destroy();
    this.host.intro.wizardStandIn = undefined;
    this.host.roastEnding.roastStick?.destroy();
    this.host.roastEnding.roastStick = undefined;
    this.host.cinema.letterbox?.forEach((bar) => bar.remove());
    this.host.cinema.letterbox = undefined;
    this.host.cinema.vignette?.remove();
    this.host.cinema.vignette = undefined;
    this.host.cinema.moonShaft?.destroy();
    this.host.cinema.moonShaft = undefined;
    this.host.cinema.groundCrack?.destroy();
    this.host.cinema.groundCrack = undefined;
    this.host.cinema.dollyBase = undefined;
    this.host.swordPlanting.swordInHands = false;
    this.host.roastEnding.roasting = false;
    this.host.life.fireflyLevel = 0;
    for (const fly of this.host.life.fireflies) fly.bb.destroy();
    this.host.life.fireflies.length = 0;
    this.host.life.daylifeLevel = 0;
    for (const b of this.host.life.butterflies) b.bb.destroy();
    this.host.life.butterflies.length = 0;
    for (const l of this.host.life.leaves) l.bb.destroy();
    this.host.life.leaves.length = 0;
    this.host.cinema.creditsRoll?.remove();
    this.host.cinema.creditsRoll = undefined;
    if (window.hd3d === this.host.world3d?.params) window.hd3d = undefined;
    setCurrentWorld3D(undefined);
    this.host.world3d?.dispose();
    this.host.world3d = undefined;
    if (this.host.camera) this.host.camera.world3d = undefined;
    this.host.dialogCam.camShiftTween?.stop();
    this.host.dialogCam.camShiftTween = undefined;
    this.host.dialogCam.camShifting = false;
    this.host.cutsceneActive = false;
    this.host.view.cutsceneHeroLight = 1;
    this.host.dialog.dialogNpcWorld = undefined;
    this.host.npcManager?.destroy();
    this.host.dialog.dialogOverlay?.destroy();
    this.host.dialog.dialogOverlay = undefined;
    this.host.hand.itemGetOverlay?.destroy();
    this.host.hand.itemGetOverlay = undefined;
    this.host.hand.itemGetOpen = false;
    this.host.pause.pauseMenu?.destroy();
    this.host.pause.pauseMenu = undefined;
    this.host.pause.pauseTouchButton?.destroy();
    this.host.pause.pauseTouchButton = undefined;
    this.host.actions.actionButtons?.destroy();
    this.host.actions.actionButtons = undefined;
    this.host.actions.controlsHint?.destroy();
    this.host.actions.controlsHint = undefined;
    this.host.orders.orderOverlay?.destroy();
    this.host.orders.orderOverlay = undefined;
    this.host.forage.foraging?.destroy();
    this.host.forage.foraging = undefined;
    this.host.itemManager?.destroy();
    this.host.machines.placementHints?.destroy();
    this.host.machines.placementHints = undefined;
    this.host.bumps.heroThought?.destroy();
    this.host.bumps.heroThought = undefined;
    this.host.forage.bagStash?.destroy();
    this.host.forage.bagStash = undefined;
    this.host.valley.oldRoad?.destroy();
    this.host.valley.oldRoad = undefined;
    this.host.valley.gardenMist?.destroy();
    this.host.valley.gardenMist = undefined;
    this.host.forage.mushroomKin?.destroy();
    this.host.forage.mushroomKin = undefined;
    this.host.forge.forging?.hammer.destroy();
    this.host.forge.forging = undefined;
    this.host.forage.shuiWave?.destroy();
    this.host.forage.shuiWave = undefined;
    this.host.forage.shuiWaved = false;
    this.host.forge.furnaceAsk?.destroy();
    this.host.forge.furnaceAsk = undefined;
    this.host.verbs.actionPrompt?.destroy();
    this.host.verbs.actionPrompt = undefined;
    this.host.swing.swordSlash?.destroy();
    // Truncar in place (length = 0) esvazia também o array tipado — é o mesmo objeto — então
    // nenhum campo fica segurando props destruídos até o próximo create reatribuí-lo.
    for (const { list } of this.host.props.propRegistry) {
      list.forEach((p) => p.destroy());
      list.length = 0;
    }
    this.host.props.propRegistry = [];
    this.host.carry.backItemSwingTimer?.remove();
    this.host.carry.backItemSwingTimer = undefined;
    this.host.boot.backItem?.destroy();
    this.host.boot.backItem = undefined;
    this.host.carry.backItemBb?.destroy();
    this.host.carry.backItemBb = undefined;
    this.host.steps.breathingTween?.destroy();
    this.host.steps.breathingTween = undefined;
    this.host.steps.footprints.length = 0;
    this.host.steps.footprintPool.length = 0;
    this.host.torch.torchFlameBb?.destroy();
    this.host.torch.torchFlameBb = undefined;
    this.host.torch.torchGutter.level = 1.0;
    this.host.torch.torchGutter.velocity = 0;
    this.host.torch.torchEmberTimer = 0;
    this.host.swing.swordSlash = undefined;
    this.host.actions.useBufferMs = 0;
    if (this.host.tweens) this.host.tweens.timeScale = 1;
  }
}
